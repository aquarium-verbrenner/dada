public class MiniCalculator {
    public int value1;
    public int value2;

    public void add() {
        System.out.println(value1 + value2);
        // return value1 + value2;
    }

    public void substract() {
        System.out.println(value1 - value2);
    }

    public void multiply() {
        System.out.println(value1 * value2);
    }

    public void divide() {
        System.out.println(value1 / value2);
    }
}